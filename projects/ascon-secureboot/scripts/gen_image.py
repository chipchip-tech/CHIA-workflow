#!/usr/bin/env python3
"""Generate the fake 4 KiB firmware image and its Ascon-Hash256 digests.

Writes:
  sw/image.h         image bytes, stored digests, tamper position (for boot.c)
  sw/expected.json   expected digests (read by the loop to check DIGEST_*)

Digests come from ascon.py (pyascon) in the ascon-verilog repo at the pinned
commit, the reference the RTL itself is tested against.

Usage:
    python3 scripts/gen_image.py --ascon-py ~/ascon-verilog/ascon.py
    python3 scripts/gen_image.py            # clones ascon-verilog into a temp dir
"""

import argparse
import importlib.util
import json
import os
import random
import subprocess
import tempfile

from prepare_rtl import PINNED_COMMIT, REPO_URL

IMAGE_SIZE = 4096
SEED = 0x5EC0B007
TAMPER_OFFSET = 1234   # byte flipped by boot_tamper (-DTAMPER)
TAMPER_MASK = 0x08
PARTIAL_SIZE = IMAGE_SIZE - 3   # boot_partial (-DPARTIAL): last RoCC word has 5 bytes
HERE = os.path.dirname(os.path.abspath(__file__))
SW_DIR = os.path.join(HERE, "..", "sw")


def load_ascon(path: str):
    spec = importlib.util.spec_from_file_location("ascon", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def make_image() -> bytes:
    rng = random.Random(SEED)
    return bytes(rng.getrandbits(8) for _ in range(IMAGE_SIZE))


def c_bytes(data: bytes, indent: str = "    ") -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return ",\n".join(indent + r for r in rows)


def write_header(path: str, image: bytes, digest: bytes, tamper_digest: bytes,
                 partial_digest: bytes):
    text = f"""\
// image.h: GENERATED by projects/ascon-secureboot/scripts/gen_image.py. DO NOT EDIT.
// Fake firmware image ({IMAGE_SIZE} bytes, random.Random(0x{SEED:08X})) and its
// Ascon-Hash256 digest computed with ascon.py from ascon-verilog@{PINNED_COMMIT[:12]}.
#ifndef IMAGE_H
#define IMAGE_H

#include <stdint.h>

#define IMAGE_SIZE {IMAGE_SIZE}
#define TAMPER_OFFSET {TAMPER_OFFSET}
#define TAMPER_MASK 0x{TAMPER_MASK:02x}
#define PARTIAL_SIZE {PARTIAL_SIZE}

// Digest "stored" next to the image, as a boot ROM would hold it.
static const uint8_t image_digest[32] = {{
{c_bytes(digest)}
}};

// For reference only (the loop checks it): digest after the tamper bit flip.
// {tamper_digest.hex()}

// boot_partial (-DPARTIAL) hashes only the first PARTIAL_SIZE bytes.
static const uint8_t partial_digest[32] __attribute__((unused)) = {{
{c_bytes(partial_digest)}
}};

// Writable so that -DTAMPER can flip a bit before hashing.
static uint8_t image[IMAGE_SIZE] __attribute__((aligned(8))) = {{
{c_bytes(image)}
}};

#endif  // IMAGE_H
"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ascon-py", help="path to ascon.py (default: clone ascon-verilog)")
    ap.add_argument("--out-dir", default=SW_DIR)
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        path = args.ascon_py
        if path is None:
            src = os.path.join(tmp, "ascon-verilog")
            subprocess.run(["git", "clone", "-q", REPO_URL, src], check=True)
            subprocess.run(["git", "-C", src, "checkout", "-q", PINNED_COMMIT], check=True)
            path = os.path.join(src, "ascon.py")
        ascon = load_ascon(os.path.expanduser(path))

    image = make_image()
    tampered = bytearray(image)
    tampered[TAMPER_OFFSET] ^= TAMPER_MASK
    digest = ascon.ascon_hash(image, "Ascon-Hash256", 32)
    tamper_digest = ascon.ascon_hash(bytes(tampered), "Ascon-Hash256", 32)
    partial_digest = ascon.ascon_hash(image[:PARTIAL_SIZE], "Ascon-Hash256", 32)

    out_dir = os.path.abspath(args.out_dir)
    write_header(os.path.join(out_dir, "image.h"), image, digest, tamper_digest,
                 partial_digest)
    expected = {
        "image_size": IMAGE_SIZE,
        "seed": SEED,
        "tamper_offset": TAMPER_OFFSET,
        "tamper_mask": TAMPER_MASK,
        "partial_size": PARTIAL_SIZE,
        "ascon_verilog_commit": PINNED_COMMIT,
        "digest": {"boot_good": digest.hex(), "boot_tamper": tamper_digest.hex(),
                   "boot_partial": partial_digest.hex()},
        # Sanity vector: Ascon-Hash256("") from the same ascon.py.
        "empty_digest": ascon.ascon_hash(b"", "Ascon-Hash256", 32).hex(),
    }
    with open(os.path.join(out_dir, "expected.json"), "w", encoding="utf-8") as f:
        json.dump(expected, f, indent=2)
        f.write("\n")
    print(json.dumps(expected["digest"], indent=2))


if __name__ == "__main__":
    main()
