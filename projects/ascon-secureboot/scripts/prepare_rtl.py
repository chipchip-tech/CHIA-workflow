#!/usr/bin/env python3
"""Merge the ascon-verilog sources into ONE file: rtl/AsconCoreV4.sv.

The upstream files use `include and declare localparams/typedefs at $unit
scope, selecting the variant with `define V<n>. Chipyard copies a BlackBox
resource file as-is into gen-collateral, so we ship a single self-contained
file instead:

  * `define V4 at the top (64-bit bus, UROL=1),
  * config.sv, functions.sv, asconp.sv, register.sv, ascon_core.sv in that
    order, with every `include line removed (the INCL_* guards are kept),
  * a thin wrapper module AsconCoreV4 with plain logic ports. It only casts
    mode/bdi_type to the enum types ascon_core expects, so a Chisel BlackBox
    never connects a UInt to an enum-typed port (Verilator ENUMVALUE).

Usage:
    python3 scripts/prepare_rtl.py                      # clones into a temp dir
    python3 scripts/prepare_rtl.py --src ~/ascon-verilog  # existing checkout
"""

import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile

REPO_URL = "https://github.com/rprimas/ascon-verilog.git"
PINNED_COMMIT = "e1069549a1895f376391530a1842694ea8bb044b"  # 2026-04-13
SOURCES = ["config.sv", "functions.sv", "asconp.sv", "register.sv", "ascon_core.sv"]
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "rtl", "AsconCoreV4.sv")

HEADER = """\
// AsconCoreV4.sv: GENERATED by projects/ascon-secureboot/scripts/prepare_rtl.py
// DO NOT EDIT. Regenerate with the script instead.
//
// Source : {url}
// Commit : {commit}
// Files  : {files}
// Variant: V4 (CCW=64-bit data bus, UROL=1 round per cycle)
// License: CC0 1.0 Universal (see the upstream LICENSE), same as upstream.
//
// The upstream include directives are removed; what they pulled in follows
// below in dependency order. AsconCoreV4 (end of file) is the module a Chisel
// BlackBox should instantiate.

`define V4
"""

WRAPPER = """
// ---------------------------------------------------------------------------
// AsconCoreV4: plain-logic-port wrapper around ascon_core (no added logic).
// mode and bdi_type take the raw 4-bit values of mode_t / data_t:
//   mode    : 0 M_INVALID, 1 M_AEAD128_ENC, 2 M_AEAD128_DEC, 3 M_HASH256,
//             4 M_XOF128, 5 M_CXOF128
//   bdi_type: 0 D_INVALID, 1 D_NONCE, 2 D_AD, 3 D_MSG, 4 D_TAG, 5 D_HASH
// ---------------------------------------------------------------------------
module AsconCoreV4 (
    input  logic        clk,
    input  logic        rst,
    input  logic [63:0] key,
    input  logic        key_valid,
    output logic        key_ready,
    input  logic [63:0] bdi,
    input  logic [ 7:0] bdi_valid,
    output logic        bdi_ready,
    input  logic [ 3:0] bdi_type,
    input  logic        bdi_eot,
    input  logic        bdi_eoi,
    input  logic [ 3:0] mode,
    output logic [63:0] bdo,
    output logic        bdo_valid,
    input  logic        bdo_ready,
    output logic [ 3:0] bdo_type,
    output logic        bdo_eot,
    input  logic        bdo_eoo,
    output logic        auth,
    output logic        auth_valid
);

  data_t bdo_type_e;

  ascon_core u_ascon_core (
      .clk       (clk),
      .rst       (rst),
      .key       (key),
      .key_valid (key_valid),
      .key_ready (key_ready),
      .bdi       (bdi),
      .bdi_valid (bdi_valid),
      .bdi_ready (bdi_ready),
      .bdi_type  (data_t'(bdi_type)),
      .bdi_eot   (bdi_eot),
      .bdi_eoi   (bdi_eoi),
      .mode      (mode_t'(mode)),
      .bdo       (bdo),
      .bdo_valid (bdo_valid),
      .bdo_ready (bdo_ready),
      .bdo_type  (bdo_type_e),
      .bdo_eot   (bdo_eot),
      .bdo_eoo   (bdo_eoo),
      .auth      (auth),
      .auth_valid(auth_valid)
  );

  assign bdo_type = bdo_type_e;

endmodule
"""

INCLUDE_RE = re.compile(r'^\s*`include\s+"[^"]+"\s*$')


def git(*args, cwd):
    return subprocess.run(["git", *args], cwd=cwd, check=True,
                          capture_output=True, text=True).stdout.strip()


def checkout(src: str | None, tmp: str) -> str:
    if src is None:
        src = os.path.join(tmp, "ascon-verilog")
        subprocess.run(["git", "clone", "-q", REPO_URL, src], check=True)
        git("checkout", "-q", PINNED_COMMIT, cwd=src)
    head = git("rev-parse", "HEAD", cwd=src)
    if head != PINNED_COMMIT:
        sys.exit(f"{src} is at {head}, expected {PINNED_COMMIT}. "
                 f"Run: git -C {src} checkout {PINNED_COMMIT}")
    return src


def merge(rtl_dir: str) -> str:
    parts = [HEADER.format(url=REPO_URL, commit=PINNED_COMMIT,
                           files=", ".join(f"rtl/{f}" for f in SOURCES))]
    for name in SOURCES:
        with open(os.path.join(rtl_dir, name), encoding="utf-8") as f:
            lines = f.read().splitlines()
        kept = [l for l in lines if not INCLUDE_RE.match(l)]
        parts.append(f"\n// ===== begin rtl/{name} =====\n")
        parts.append("\n".join(kept).rstrip() + "\n")
        parts.append(f"// ===== end rtl/{name} =====\n")
    parts.append(WRAPPER)
    text = "".join(parts)
    assert not any(INCLUDE_RE.match(l) for l in text.splitlines()), \
        "an include directive survived the merge"
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", help="existing ascon-verilog checkout (default: clone)")
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        src = checkout(os.path.expanduser(args.src) if args.src else None, tmp)
        text = merge(os.path.join(src, "rtl"))

    out = os.path.abspath(args.out)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    print(f"wrote {out}\nsha256 {sha}")


if __name__ == "__main__":
    main()
