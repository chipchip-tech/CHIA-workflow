"""Measure RocketTile Fmax again once the config audit removed SoC blocks.

Fmax in this project is the Yosys + OpenSTA result on RocketTile (flow v2, fixed
period). The audited blocks sit outside the tile, but the tile still sees the
address map (TLB/PMA checks, legal-address decode), so its RTL can change. Four
points, each a build + synth/STA of RocketTile:

  base      RocketConfig                         (cached baseline of rocket_fmax.py)
  cfg       fragments ++ RocketConfig            (audit config, no Fmax patch)
  best      RocketConfig + best.patch            (the Fmax loop result)
  best_cfg  fragments ++ RocketConfig + best.patch   (+ gate: ISA + benchmark mcycle)

  chia job submit --no-wait --submission-id fmax-soc --working-dir . -- \\
      python measure_soc.py --run-name soc-fmax --exclude-isa rv64ui-p-ma_data \\
      --patch-file ~/rocket-fmax-out/m3/patches/best.patch

The loop writes the config class to RocketFmaxAudit.scala (removed afterwards) and
leaves rocket-chip with best.patch applied.
"""

import argparse
import hashlib
import json
import time
from datetime import datetime
from pathlib import Path

import ray

import fmax_nodes as N
from config_audit import config_text
from rocket_fmax import (build, build_errors, compare_gate, ensure_baseline, export_profile, print_synth,
                         save_build, save_gate, save_synth, write)
from chia.base.ChiaFunction import get
from chia.base.bypass import Bypass
from chia.base.cache import start_cache, stop_cache
from chia.trace.profiler import start_collector, stop_collector

HERE = Path(__file__).resolve().parent
EXP_YAML = HERE / "exp.yaml"
FRAGMENTS = ["new testchipip.soc.WithNoScratchpads", "new chipyard.config.WithNoBusErrorDevices"]


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--patch-file", required=True, help="best.patch of the Fmax loop (git diff in rocket-chip)")
    p.add_argument("--fragments", nargs="+", default=FRAGMENTS, help="config fragments kept by the audit")
    p.add_argument("--period-ns", type=float, default=21.2)
    p.add_argument("--synth-flow", choices=sorted(N.SYNTH_FLOWS), default="v2")
    p.add_argument("--repeat-seed", type=int, default=7, help="only used if the baseline is not cached")
    p.add_argument("--run-name", default=None)
    p.add_argument("--out-dir", default="~/rocket-fmax-out")
    p.add_argument("--cache-dir", default="~/chia_cache")
    p.add_argument("--make-jobs", type=int, default=16)
    p.add_argument("--build-timeout", type=int, default=3600)
    p.add_argument("--exclude-isa", nargs="*", default=[])
    a = p.parse_args()
    a.out_dir = str(Path(a.out_dir).expanduser())
    a.run_name = a.run_name or datetime.now().strftime("soc-fmax-%Y%m%d-%H%M%S")
    return a


def rtl_digest(rtl) -> str:
    h = hashlib.sha256()
    for name, text in sorted({**rtl.files, **rtl.blackboxes}.items()):
        h.update(name.encode() + b"\0" + text.encode() + b"\0")
    return h.hexdigest()[:16]


def rtl_diff(a, b) -> str:
    """Modules whose text differs between two TileRTLs."""
    def mods(rtl):
        out = {}
        for text in list(rtl.files.values()) + list(rtl.blackboxes.values()):
            out.update(N._split_modules(text))
        return out
    ma, mb = mods(a), mods(b)
    changed = sorted(m for m in ma.keys() & mb.keys() if ma[m] != mb[m])
    only_a, only_b = sorted(ma.keys() - mb.keys()), sorted(mb.keys() - ma.keys())
    if not (changed or only_a or only_b):
        return "giống hệt"
    parts = [f"đổi {len(changed)}: {', '.join(changed[:12])}" + (" ..." if len(changed) > 12 else "")] if changed else []
    parts += [f"mất {', '.join(only_a[:8])}"] if only_a else []
    parts += [f"thêm {', '.join(only_b[:8])}"] if only_b else []
    return "; ".join(parts)


def build_point(a, out: Path, snap: dict, name: str, patch: str, frags: list[str]):
    """Set the tree (rocket-chip patch + config file), build, return (artifact, TileRTL)."""
    d = out / "runs" / name
    get(N.reset_rocket.chia_remote(snap["rocket_head"], patch))
    config = N.CONFIG
    if frags:
        config = f"RocketFmaxMeasure{''.join(w.capitalize() for w in name.split('_'))}"
        text = config_text({config: frags}, "// Generated by projects/rocket-fmax/measure_soc.py; "
                                            "removed after the build.")
        write(d / "RocketFmaxAudit.scala", text)
        get(N.write_audit_config.chia_remote(text))
    t0 = time.time()
    try:
        art = get(build(a, name, config=config))
    finally:
        if frags:
            get(N.write_audit_config.chia_remote(None))
    save_build(d, art)
    if not art.success:
        raise SystemExit(f"{name}: build lỗi ({config}):\n{build_errors(art)}")
    print(f"{name}: build {config} ok ({(time.time() - t0) / 60:.1f} min)", flush=True)
    return art, get(N.extract_tile_rtl.chia_remote(art))


def run(a, out: Path):
    elfs = get(N.load_test_elfs.chia_remote())
    snap = get(N.tree_snapshot.chia_remote())
    write(out / "runs" / "tree_snapshot.json", json.dumps(snap, indent=2))
    patch = Path(a.patch_file).expanduser().read_text()
    if not patch.strip():
        raise SystemExit(f"{a.patch_file} rỗng")
    write(out / "patches" / "best.patch", patch)
    get(N.write_audit_config.chia_remote(None))

    base = ensure_baseline(a, out, elfs, snap)
    points = {"base": {"rtl": base["rtl"], "synth": base["synth"]}}
    plan = [("cfg", "", a.fragments), ("best", patch, []), ("best_cfg", patch, a.fragments)]
    synth_refs, gate_ref = {}, None
    # Builds share the chipyard tree, so they run one after another; synth/STA and
    # the gate of a finished build run meanwhile on the other workers.
    for name, p, frags in plan:
        print(f"\n######## {name}: patch={'best' if p else '-'}, fragments={frags or '-'}", flush=True)
        art, rtl = build_point(a, out, snap, name, p, frags)
        points[name] = {"rtl": rtl}
        synth_refs[name] = N.synth_sta.chia_remote(rtl, a.period_ns, a.synth_flow)
        if name == "best_cfg":
            gate_ref = N.run_gate.chia_remote(art, elfs)
    for name, ref in synth_refs.items():
        s = get(ref)
        points[name]["synth"] = s
        save_synth(out / "runs" / name, s)
        print_synth(name, s)
    gate = get(gate_ref)
    save_gate(out / "runs" / "best_cfg", gate)
    isa_ok, cyc_ok, why = compare_gate(base["gate"], gate, a.exclude_isa)
    report(a, out, points, isa_ok, cyc_ok, why)


def report(a, out: Path, points: dict, isa_ok: bool, cyc_ok: bool, why: list[str]):
    rows = [("base", "RocketConfig", "-"), ("cfg", "fragment audit", "-"),
            ("best", "RocketConfig", "best.patch"), ("best_cfg", "fragment audit", "best.patch")]
    lines = [f"# Fmax RocketTile sau khi bỏ khối SoC ({a.run_name})", "",
             f"Flow `{a.synth_flow}`, chu kỳ cố định {a.period_ns} ns, sky130hd tt. Fragment: "
             + ", ".join(f"`{f}`" for f in a.fragments) + ".", "",
             "| Điểm | Config | Patch | Worst slack (ns) | Đường găng (ns) | Fmax (MHz) | Area tile (um2) "
             "| RTL tile (sha) | Đường găng |",
             "|---|---|---|---|---|---|---|---|---|"]
    for name, cfg, p in rows:
        s, rtl = points[name]["synth"], points[name]["rtl"]
        ok = s.success and s.worst_slack_ns is not None
        delay = f"{a.period_ns - s.worst_slack_ns:.3f}" if ok else "lỗi"
        lines.append(f"| {name} | {cfg} | {p} | {f'{s.worst_slack_ns:.3f}' if ok else s.error} | {delay} | "
                     f"{f'{s.fmax_mhz:.2f}' if s.fmax_mhz else ''} | {s.area_um2 or 0:.0f} | {rtl_digest(rtl)} | "
                     f"`{s.crit_start}` -> `{s.crit_end}` |")
    lines += ["", "RTL `RocketTile` (từng module, đã gồm SRAM model):", "",
              f"- base vs cfg: {rtl_diff(points['base']['rtl'], points['cfg']['rtl'])}",
              f"- best vs best_cfg: {rtl_diff(points['best']['rtl'], points['best_cfg']['rtl'])}", "",
              f"Gate `best_cfg` (so với baseline): ISA {'pass' if isa_ok else 'FAIL'}, mcycle benchmark "
              f"{'giữ nguyên' if cyc_ok else 'ĐỔI'}" + (f" ({'; '.join(why)})" if why else "") + ".", "",
              "Area tile ở đây là của luồng `v2` (flatten); area phần ngoài tile xem `audit.md` của audit."]
    write(out / "soc_fmax.md", "\n".join(lines) + "\n")
    print("\n" + "\n".join(lines), flush=True)


def main():
    a = parse_args()
    out = Path(a.out_dir) / a.run_name
    for sub in ("patches", "runs", "profile"):
        (out / sub).mkdir(parents=True, exist_ok=True)
    write(out / "args.json", json.dumps(vars(a), indent=2))
    print(f"run {a.run_name}: output {out}", flush=True)
    ray.init(address="auto", namespace="rocket_fmax", ignore_reinit_error=True)
    start_collector(log_dir=str(out / "profile"))
    start_cache(size=4, units="GB", cache_dir_path=a.cache_dir, yaml_path=str(EXP_YAML))
    bypass = Bypass(yaml_path=str(EXP_YAML))
    for fn in ("extract_tile_rtl", "run_gate", "synth_sta"):
        bypass.set_provider(fn, N.cache_provider)
        bypass.set_cond(fn, N.cache_hit_cond)
    try:
        run(a, out)
    finally:
        try:
            get(N.write_audit_config.chia_remote(None))
        except Exception as e:                                       # noqa: BLE001
            print(f"không xoá được {N.AUDIT_CONFIG_FILE}: {e}")
        try:
            stop_collector()
        finally:
            stop_cache()
            export_profile(out)
    print(f"done: {out}")


if __name__ == "__main__":
    main()
